using 暗潮航线.规则;

namespace 暗潮航线.规则.测试;

public class 下注轮测试
{
    /// <summary>默认：五人按 0→1→2→3→4 行动，底注 1，进入本轮时每人剩 100。</summary>
    /// <summary>
    /// 默认局面：五人按 0→1→2→3→4 行动，底注 1，进入本轮时每人剩 100。
    /// 起始池不指定时按“本局参与者都交过底注”计算——真实流程里底注在下注轮之前收取，
    /// 池为空会让任何人都开不了注（最高开注额等于池）。
    /// </summary>
    private static 下注轮 新建(
        int 底注 = 1,
        int? 起始池 = null,
        int 座位数 = 5,
        int[]? 余额 = null,
        IReadOnlyList<int>? 行动顺序 = null)
    {
        行动顺序 ??= Enumerable.Range(0, 座位数).ToArray();
        // 余额按行动顺序逐人给；不指定时每人 100，长度与行动顺序一致。
        余额 ??= Enumerable.Repeat(100, 行动顺序.Count).ToArray();
        return new 下注轮(底注, 起始池 ?? 底注 * 行动顺序.Count, 座位数, 行动顺序, 余额);
    }

    [Fact]
    public void 无待跟注额时可以过牌或开注而不能主动弃牌()
    {
        var 轮 = 新建();

        var 合法 = 轮.生成合法动作();

        Assert.True(合法.可过牌);
        Assert.False(合法.可跟注);
        Assert.Equal(0, 合法.跟注额);
        Assert.True(合法.可加注);
        Assert.Equal(2, 合法.最小加注目标额);   // 首次开注至少 2 倍底注
        Assert.False(合法.可弃牌);
    }

    [Fact]
    public void 面对开注时最小完整加注在目标额上再加一个完整幅度()
    {
        var 轮 = 新建(座位数: 3);
        轮.加注到(2);   // 座位 0 开注 2

        var 合法 = 轮.生成合法动作();   // 座位 1

        Assert.False(合法.可过牌);
        Assert.Equal(2, 合法.跟注额);
        Assert.Equal(4, 合法.最小加注目标额);
    }

    [Fact]
    public void 开注额成为后续最小完整加价幅度()
    {
        // 文档例：先开注 6，下一次完整加注至少加到本轮累计 12。
        var 轮 = 新建(起始池: 23, 座位数: 3);
        轮.加注到(6);

        Assert.Equal(12, 轮.生成合法动作().最小加注目标额);
    }

    [Fact]
    public void 无人下注时最高开注额等于池而不是零()
    {
        // 规则：无人下注时 C＝0，最高开注额就是 P。
        // 如果写成 P＋2C，池为空时会算出 0，任何开注都会被拒绝。
        var 轮 = 新建(起始池: 22, 座位数: 2);

        var 合法 = 轮.生成合法动作();

        Assert.Equal(0, 合法.跟注额);
        Assert.Equal(2, 合法.最小加注目标额);      // 至少 2 倍底注
        Assert.Equal(22, 合法.最大加注目标额);     // 无人下注时最高开注额就是 P
    }

    [Fact]
    public void 底池限注按池加两倍跟注额封顶()
    {
        // 文档 4.3 的例子：行动前池 P＝20，需要跟 C＝6，本次最多新增 32。
        // 两人各交底注 1，本轮之前累计 18，则开注前池为 20。
        // 文档 4.3：行动前池为 20（此时已含座位 0 待响应的 6）。
        // 两人各交底注 1，本轮之前累计 12，则开注前池为 14，开注 6 之后正好 20。
        var 轮 = 新建(起始池: 14, 座位数: 2, 余额: new[] { 100, 100 });
        轮.加注到(6);   // 座位 0 开注 6，池变 20

        var 合法 = 轮.生成合法动作();   // 座位 1：跟 6，本次最多新增 20＋12＝32

        Assert.Equal(6, 合法.跟注额);
        Assert.Equal(32, 合法.最大加注目标额);
    }

    [Fact]
    public void 不足完整幅度的全下不更新幅度也不授予加价权()
    {
        // 文档 4.4 例：A 开注 10，B 全下到 15（只增加 5）；此后没有其他加价时 A 不能再次加注。
        // 三人桌：B 全下后还有 C 可以响应，所以本轮不会因为只剩一人而立刻结束。
        var 轮 = 新建(起始池: 12, 座位数: 3, 余额: new[] { 100, 15, 100 });
        轮.加注到(10);   // 座位 0 开注 10，最小完整加价幅度定为 10
        轮.全下();       // 座位 1 只有 15，跟 10 后剩 5，不足额加价
        轮.跟注();       // 座位 2 跟到 15

        Assert.True(轮.已全下座位(1));
        Assert.Equal(15, 轮.目标额);
        Assert.Equal(10, 轮.最小完整加价);   // 不足额全下不更新这一档

        var 合法 = 轮.生成合法动作();   // 回到座位 0
        Assert.Equal(5, 合法.跟注额);
        Assert.False(轮.有加价权座位(0));   // 只增加了 5，不到一个完整幅度
        Assert.False(合法.可加注);
        Assert.Throws<规则拒绝异常>(() => 轮.加注到(20));
    }

    [Fact]
    public void 累计增长达到完整幅度后重新获得加价权()
    {
        // 文档例：短额全下把目标累计推到 20，A 面临新增 10，重新获得加价权。
        var 轮 = 新建(起始池: 12, 座位数: 4, 余额: new[] { 100, 15, 20, 100 });
        轮.加注到(10);   // 座位 0 开注 10
        轮.全下();       // 座位 1 全下到 15，只增加 5
        Assert.False(轮.有加价权座位(0));
        轮.全下();       // 座位 2 全下到 20，累计增加 10
        轮.跟注();       // 座位 3 跟到 20

        var 合法 = 轮.生成合法动作();   // 回到座位 0

        Assert.Equal(10, 合法.跟注额);
        // 座位 0 上次行动时目标额是 10，现在 20，累计增加 10，等于完整加价幅度，重新获得加价权。
        Assert.True(合法.可加注);
    }

    [Fact]
    public void 跟齐后本轮结束且普通池计入全部投入()
    {
        var 轮 = 新建(底注: 1, 座位数: 3);
        轮.加注到(3);
        轮.跟注();
        轮.跟注();

        Assert.True(轮.本轮结束);
        // 起始池 3（三份底注）+ 本轮各投 3。
        Assert.Equal(12, 轮.当前普通池);
        Assert.Equal(3, 轮.统计在局人数());
    }

    [Fact]
    public void 弃牌者退出本局但已投入的钱留在池里()
    {
        var 轮 = 新建(起始池: 23, 座位数: 3);
        轮.加注到(5);
        轮.跟注();
        轮.弃牌();   // 座位 2 面对 5 弃牌

        Assert.True(轮.本轮结束);
        Assert.Equal(2, 轮.统计在局人数());
        Assert.True(轮.已弃牌座位(2));
        Assert.Equal(33, 轮.当前普通池);   // 起始 23 + 5 + 5
    }

    [Fact]
    public void 筹码不足跟注时全下而不是变成负余额()
    {
        var 轮 = 新建(起始池: 10, 座位数: 2, 余额: new[] { 100, 3 });
        轮.加注到(10);

        var 合法 = 轮.生成合法动作();   // 座位 1 只有 3

        Assert.Equal(3, 合法.跟注额);
        Assert.True(合法.可全下);
        轮.全下();

        Assert.Equal(0, 轮.查看剩余筹码(1));
        Assert.True(轮.已全下座位(1));
        Assert.Equal(3, 轮.查看本轮投入(1));
    }

    [Fact]
    public void 只剩一人可行动时本轮直接结束()
    {
        // 座位 1 没有筹码，等同全下；只剩座位 0 有筹码，不能继续向无人能跟的池下注。
        var 轮 = 新建(座位数: 2, 余额: new[] { 100, 0 });

        Assert.True(轮.本轮结束);
        Assert.Equal(-1, 轮.当前行动座位);
    }

    [Fact]
    public void 不足额跟注的全下之后本轮结束()
    {
        // 开了 30 的注，所以开注前池至少要有 30。
        var 轮 = 新建(起始池: 30, 座位数: 2, 余额: new[] { 100, 20 });
        轮.加注到(30);
        轮.全下();   // 座位 1 只有 20，跟不全

        // 座位 1 已经全下，本轮只剩座位 0 一人可行动，可以直接结束。
        Assert.True(轮.本轮结束);
        Assert.Equal(80, 轮.当前普通池);   // 30 + 30 + 20
        Assert.Equal(20, 轮.查看本轮投入(1));
    }

    [Fact]
    public void 行动顺序按传入名单绕圈而不是按座位号()
    {
        // 入座顺序 3→1→4，行动应从 3 开始。
        var 轮 = 新建(座位数: 5, 行动顺序: new[] { 3, 1, 4 });

        Assert.Equal(3, 轮.当前行动座位);
        轮.过牌();
        Assert.Equal(1, 轮.当前行动座位);
        轮.过牌();
        Assert.Equal(4, 轮.当前行动座位);
    }

    [Fact]
    public void 拒绝重复座位与过少玩家()
    {
        Assert.Throws<ArgumentException>(() => 新建(座位数: 3, 行动顺序: new[] { 0, 0, 1 }));
        Assert.Throws<ArgumentException>(() => 新建(座位数: 3, 行动顺序: new[] { 0 }));
        Assert.Throws<ArgumentException>(() => 新建(座位数: 3, 行动顺序: new[] { 0, 1, 9 }));
        // 余额按行动顺序给，长度不符要拒绝。
        Assert.Throws<ArgumentException>(() => 新建(座位数: 3, 行动顺序: new[] { 0, 1, 2 }, 余额: new[] { 1, 2 }));
    }

    [Fact]
    public void 本轮不存在时不能操作()
    {
        var 轮 = 新建(座位数: 2);
        轮.过牌();
        轮.过牌();

        Assert.True(轮.本轮结束);
        Assert.Equal(-1, 轮.当前行动座位);
        Assert.Throws<规则拒绝异常>(() => 轮.过牌());
        Assert.Throws<InvalidOperationException>(() => 轮.生成合法动作());
    }
}
